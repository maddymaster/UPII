#!/usr/bin/env python3
"""Does storing extractor-rule confidence on graph edges help relational retrieval?

Runs the labelled retrieval eval at several relational fusion weights under two
edge-confidence modes on the same isolated index:

- ``uniform``: every edge confidence forced to 1.0 (the behaviour before edges
  stored the rule's confidence);
- ``rule``: the confidence of the extractor rule that matched (project 0.95,
  titled person / corporate suffix 0.9, given name 0.75, acronym org 0.70).

Writes ``results/relational_REPORT.md`` and ``results/relational_results.json``.
The default relational weight (``config.fusion_weight_relational``) is reported but
not changed. Informational: always exits 0 unless the eval cannot run.

Usage:
    python eval/run_relational_eval.py
"""

from __future__ import annotations

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from eval import harness, metrics  # noqa: E402

WEIGHTS = (0.0, 0.25, 0.5, 1.0)
KS = (1, 5, 10)


def score(labels, weight):
    from upii.core.config import config

    config.fusion_weight_relational = weight
    rows = []
    for q in labels:
        relevant = q["relevant_chunk_ids"]
        if not relevant:
            continue
        ranked = harness.retrieve(q["query"], limit=max(KS))
        rows.append({k: metrics.recall_at_k(ranked, relevant, k) for k in KS}
                    | {"mrr": metrics.reciprocal_rank(ranked, relevant)})
    return {**{f"recall@{k}": round(metrics.mean(r[k] for r in rows), 4) for k in KS},
            "mrr": round(metrics.mean(r["mrr"] for r in rows), 4)}


def main() -> int:
    harness.use_isolated_index()
    labels = json.load(open(harness.LABELS_PATH))["queries"]
    harness.ingest_corpus(reset=True)

    from upii.core.config import config
    from upii.storage.db import DB

    default_weight = config.fusion_weight_relational
    db = DB()
    conn = db.get_connection()
    rule_conf = conn.execute("SELECT edge_id, confidence FROM entity_edges").fetchall()
    conn.close()
    distribution = {}
    for _, c in rule_conf:
        distribution[f"{c:.2f}"] = distribution.get(f"{c:.2f}", 0) + 1

    def set_confidences(uniform: bool):
        conn = db.get_connection()
        if uniform:
            conn.execute("UPDATE entity_edges SET confidence = 1.0")
        else:
            conn.executemany("UPDATE entity_edges SET confidence = ? WHERE edge_id = ?",
                             [(c, e) for e, c in rule_conf])
        conn.commit()
        conn.close()

    results = {"edges": len(rule_conf), "confidence_distribution": distribution,
               "default_relational_weight": default_weight, "runs": []}
    try:
        for mode in ("uniform", "rule"):
            set_confidences(uniform=(mode == "uniform"))
            for w in WEIGHTS:
                results["runs"].append({"mode": mode, "w_relational": w, **score(labels, w)})
    finally:
        config.fusion_weight_relational = default_weight
        set_confidences(uniform=False)

    lines = [
        "# Relational signal — uniform vs rule-confidence edges",
        "",
        "Generated by `python eval/run_relational_eval.py` on the labelled retrieval eval",
        f"({len(labels)} queries). Semantic weight {config.fusion_weight_semantic}, temporal "
        f"{config.fusion_weight_temporal}; relational varied. Default relational weight: "
        f"**{default_weight}**.",
        "",
        f"Edges: {len(rule_conf)}; rule confidences: "
        + ", ".join(f"{k} × {v}" for k, v in sorted(distribution.items())),
        "",
        "| w_relational | Edges | Recall@1 | Recall@5 | Recall@10 | MRR |",
        "|---|---|---|---|---|---|",
    ]
    for w in WEIGHTS:
        for mode in ("uniform", "rule"):
            r = next(x for x in results["runs"] if x["mode"] == mode and x["w_relational"] == w)
            lines.append(f"| {w} | {mode} | {r['recall@1']:.3f} | {r['recall@5']:.3f} | "
                         f"{r['recall@10']:.3f} | {r['mrr']:.3f} |")

    os.makedirs(harness.RESULTS_DIR, exist_ok=True)
    with open(os.path.join(harness.RESULTS_DIR, "relational_REPORT.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    with open(os.path.join(harness.RESULTS_DIR, "relational_results.json"), "w") as f:
        json.dump(results, f, indent=2, sort_keys=True)
        f.write("\n")
    print("\n".join(lines[8:]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
